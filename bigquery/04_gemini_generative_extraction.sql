-- ==============================================================================
-- MetaRetail AI - Multimodal Generative Extraction via Gemini 2.5 Flash
-- Uses AI.GENERATE_TABLE to parse unstructured security reports and manager notes
-- ==============================================================================

-- 1. Create Remote Model pointing to Vertex AI Gemini 2.5 Flash
CREATE OR REPLACE MODEL `PROJECT_ID.retail_enterprise_bi.gemini_flash_remote`
REMOTE WITH CONNECTION DEFAULT
OPTIONS (ENDPOINT = 'gemini-2.5-flash');

-- 2. Extract Structured Severity, Suspected SKU, Root Cause, and Recommended Action
SELECT
  incident_id,
  incident_type,
  reported_time,
  -- Strongly-typed columns generated by Gemini
  extracted.severity_grade,
  extracted.suspected_sku_or_brand,
  extracted.behavioral_pattern,
  extracted.recommended_preventative_measure
FROM
  AI.GENERATE_TABLE(
    MODEL `PROJECT_ID.retail_enterprise_bi.gemini_flash_remote`,
    (
      SELECT
        incident_id,
        incident_type,
        created_at AS reported_time,
        -- Input subquery MUST contain a column named or aliased as 'prompt'
        CONCAT(
          "You are an expert autonomous supermarket security and loss prevention auditor.\n",
          "Analyze the following computer vision incident log and extract structured data:\n",
          "Incident Type: ", incident_type, "\n",
          "Raw Description: ", description, "\n",
          "Initial Recommendation: ", recommended_action
        ) AS prompt
      FROM
        `PROJECT_ID.retail_enterprise_bi.security_incidents`
      ORDER BY created_at DESC
      LIMIT 50
    ),
    STRUCT(
      "severity_grade STRING, suspected_sku_or_brand STRING, behavioral_pattern STRING, recommended_preventative_measure STRING" AS output_schema,
      0.0 AS temperature,
      1024 AS max_output_tokens
    )
  );
